import { test, expect } from '@playwright/test';
for (const width of [320, 768, 1440]) test(`Stacked Action accordions, summary and execution at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.addInitScript(() => {
    if (location.origin !== 'http://127.0.0.1:4179' || localStorage.getItem('action-accordions-seeded')) return;
    localStorage.setItem('action-accordions-seeded', '1');
    localStorage.setItem('5s-auth-session', JSON.stringify({ authenticated: true, username: 'admin', version: 1 }));
    localStorage.setItem('five-s-demo-role', 'responsible');
    localStorage.setItem('ops-red-tag-original-reset-v1', 'done');
    localStorage.setItem('standalone-5s-actions', JSON.stringify([{ id: 'ACT-ACCORDIONS', title: 'Synthetic accordion execution', description: 'Long description '.repeat(20), source: 'Manual', sourceModule: 'manual', sourceTitle: 'Manual', plant: 'Egmore Plant', area: 'Zone B', department: 'Production', responsiblePersonId: 'USR-SIVA-KUMAR', responsiblePersonName: 'Siva Kumar', assignedTo: 'Siva Kumar', createdByUserId: 'USR-RUMESH', createdByName: 'Rumesh', reviewerId: 'USR-RUMESH', reviewerName: 'Rumesh', status: 'Assigned', priority: 'Medium', dueDate: '2030-12-20', createdAt: '2026-10-18T10:00:00Z', activityHistory: [], evidence: [] }]));
  });
  await page.goto('/actions/ACT-ACCORDIONS', { waitUntil: 'networkidle' });
  await expect(page.getByRole('tablist')).toHaveCount(0);
  const summary = page.locator('summary').filter({ hasText: /^Action Summary$/ });
  const summaryDetails = summary.locator('..');
  await expect(summaryDetails).not.toHaveAttribute('open');
  await summary.focus(); await page.keyboard.press('Enter');
  await expect(summaryDetails).toHaveAttribute('open', '');
  await expect(summaryDetails.getByText('Action Title', { exact: true })).toBeVisible();
  await summary.press('Enter'); await expect(summaryDetails).not.toHaveAttribute('open');
  const overview = page.getByRole('button', { name: 'Overview', exact: true });
  const evidence = page.getByRole('button', { name: 'Evidence', exact: true });
  const review = page.getByRole('button', { name: 'Review', exact: true });
  const positions = await Promise.all([overview, evidence, review].map(async locator => (await locator.boundingBox())!.y));
  expect(positions[0]).toBeLessThan(positions[1]); expect(positions[1]).toBeLessThan(positions[2]);
  await expect(overview).toHaveAttribute('aria-expanded', 'true');
  const container = overview.locator('../..');
  await expect(container).toHaveClass(/border/);
  await expect(container.locator('[data-slot="card"]')).toHaveCount(0);
  const unified = await container.evaluate(el => {
    const header = el.querySelector('h2')!.getBoundingClientRect();
    const body = el.querySelector('[id$="-content"]')!.getBoundingClientRect();
    const panel = el.getBoundingClientRect();
    return { gap: body.top - header.bottom, contained: body.bottom <= panel.bottom + 1 && body.left >= panel.left && body.right <= panel.right };
  });
  expect(Math.abs(unified.gap)).toBeLessThanOrEqual(1);
  expect(unified.contained).toBe(true);
  await container.screenshot({ path: `test-results/action-overview-unified-${width}.png` });
  await overview.click(); await expect(overview).toHaveAttribute('aria-expanded', 'false');
  await overview.press('Enter'); await expect(overview).toHaveAttribute('aria-expanded', 'true');
  const lockedFields = page.locator('fieldset');
  await expect(lockedFields).toHaveAttribute('disabled', '');
  await expect(page.getByPlaceholder('Describe the corrective work completed...')).toBeDisabled();
  await expect(lockedFields).toHaveCSS('filter', 'blur(4px)');
  const start = page.getByRole('button', { name: 'Start Work', exact: true });
  const fieldsBounds = (await lockedFields.boundingBox())!;
  const startBounds = (await start.boundingBox())!;
  expect(Math.abs(startBounds.x + startBounds.width / 2 - fieldsBounds.x - fieldsBounds.width / 2)).toBeLessThanOrEqual(1);
  await start.scrollIntoViewIfNeeded();
  await start.click({ trial: true });
  await container.screenshot({ path: `test-results/action-resolution-blurred-${width}.png` });
  await start.click();
  await expect(lockedFields).toHaveCSS('filter', 'none');
  const notes = page.getByPlaceholder('Describe the corrective work completed...');
  await expect(notes).toBeEnabled(); await notes.fill('Draft retained while browsing and uploading');
  await evidence.click(); await expect(evidence).toHaveAttribute('aria-expanded', 'true');
  await expect(overview).toHaveAttribute('aria-expanded', 'false');
  const file = { name: 'synthetic-evidence.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jH1sAAAAASUVORK5CYII=', 'base64') };
  await page.locator('input[type="file"]').first().setInputFiles(file);
  await expect(page.getByText('synthetic-evidence.png', { exact: true }).filter({ visible: true })).toBeVisible();
  await overview.click(); await expect(notes).toHaveValue('Draft retained while browsing and uploading');
  await page.getByRole('combobox', { name: 'Corrective Action Category', exact: true }).click();
  await page.getByRole('option', { name: 'Design / Equipment Modification', exact: true }).click();
  await page.getByRole('button', { name: 'Next: Evidence', exact: true }).click();
  await page.getByRole('button', { name: 'Submit', exact: true }).click();
  await expect(evidence).toHaveAttribute('aria-expanded', 'true');
  await expect(page.getByText('Add completion evidence before continuing to Review.', { exact: true })).toBeVisible();
  await review.click(); await page.getByRole('button', { name: 'Submit for Review', exact: true }).click();
  await expect(evidence).toHaveAttribute('aria-expanded', 'true');
  await page.locator('input[type="file"]').last().setInputFiles({ ...file, name: 'synthetic-completion.png' });
  await expect(page.getByText('synthetic-completion.png', { exact: true }).filter({ visible: true })).toBeVisible();
  const submit = page.getByRole('button', { name: 'Submit', exact: true });
  await expect(submit.locator('../..').getByRole('button')).toHaveCount(1);
  await submit.click();
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('standalone-5s-actions')!).find((action: { id: string }) => action.id === 'ACT-ACCORDIONS').status)).toBe('Pending Auditor Review');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await summary.scrollIntoViewIfNeeded(); await summary.click();
  await expect(summaryDetails).toHaveAttribute('open', '');
  await page.screenshot({ path: `test-results/action-accordions-${width}.png`, fullPage: true });
  await page.reload({ waitUntil: 'networkidle' });
  await expect(notes).toHaveCount(0); // Submitted work renders as read-only values.
  await page.evaluate(() => localStorage.setItem('five-s-demo-role', 'leader'));
  await page.reload({ waitUntil: 'networkidle' });
  await review.click();
  await page.getByRole('button', { name: 'Verify & Close', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Verify & Close', exact: true }).click();
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('standalone-5s-actions')!).find((action: { id: string }) => action.id === 'ACT-ACCORDIONS').status)).toBe('Completed');
});
