import { expect, test } from '@playwright/test';
import { seed } from './ui-batch2-helpers';

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
const photo = (name: string) => ({ name, mimeType: 'image/png', buffer: png });
for (const width of [320, 1440]) test(`Red Tag multiple identification photos ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await seed(page, 'responsible');
  await page.goto('/5s/red/create');
  await page.getByPlaceholder('e.g. Obsolete welding fixture').fill('Multiple photo fixture');
  await page.getByPlaceholder('Describe the item and its current condition.').fill('Inspect each side of the item');
  await page.getByRole('button', {name:'Usage', exact:true}).click();
  await page.getByRole('button', {name:'Unused', exact:true}).click();
  await page.getByRole('button', {name:'Create Red Tag', exact:true}).click();
  await expect(page.getByText('Add a photo to create this Red Tag.', {exact:true})).toBeVisible();
  const upload = page.getByLabel('Attach Red Tag images', {exact:true});
  await upload.setInputFiles([photo('front.png'), photo('side.png'), photo('back.png')]);
  await expect(page.getByRole('status').filter({hasText:'3 of 5 photos attached'})).toBeVisible();
  await page.getByRole('button', {name:'Preview image 2', exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('img', {name:'side.png', exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', {name:'Remove image 1', exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'2 of 5 photos attached'})).toBeVisible();
  await upload.setInputFiles({name:'invalid.txt', mimeType:'text/plain', buffer:Buffer.from('invalid')});
  await expect(page.getByText('Only image files can be uploaded as evidence.', {exact:true})).toBeVisible();
  await upload.setInputFiles([photo('top.png'), photo('bottom.png'), photo('detail.png'), photo('excess.png')]);
  await expect(page.getByText('Maximum 5 evidence images allowed.', {exact:true})).toBeVisible();
  await expect(page.getByRole('button', {name:/^Preview image /})).toHaveCount(2);
  await upload.setInputFiles([photo('top.png'), photo('bottom.png'), photo('detail.png')]);
  await expect(page.getByRole('status').filter({hasText:'5 of 5 photos attached'})).toBeVisible();
  await expect(page.getByRole('button', {name:'Upload Photos', exact:true})).toBeDisabled();
  await expect(page.getByRole('button', {name:'Take Photo', exact:true})).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  await page.getByRole('button', {name:'Create Red Tag', exact:true}).click();
  await expect(page).toHaveURL(/\/5s\/red\/RT-\d{6}$/);
  const id = new URL(page.url()).pathname.split('/').pop()!;
  const saved = await page.evaluate(id => JSON.parse(localStorage.getItem('five-s-red-tags-v1')!).find((tag: {id:string}) => tag.id === id), id);
  expect(saved.identificationEvidence.map((item: {name:string}) => item.name)).toEqual(['side.png','back.png','top.png','bottom.png','detail.png']);
  expect(saved.imageUrl).toBe(saved.identificationEvidence[0].url);
  await page.reload();
  await expect(page.getByRole('button', {name:/^View identification image /})).toHaveCount(5);
  // Details use the full page width; QR is available on demand in the header.
  await expect(page.getByRole('button', {name:'View QR', exact:true})).toHaveCount(1);
  await expect(page.getByText('Scan to view Red Tag', {exact:true})).toHaveCount(0);
  const details = await page.locator('[data-slot="card"]').filter({has:page.getByRole('heading', {name:'Item Details', exact:true})}).boundingBox();
  const history = await page.getByTestId('red-tag-history').boundingBox();
  expect(Math.abs(details!.x-history!.x)).toBeLessThanOrEqual(1);
  expect(Math.abs(details!.width-history!.width)).toBeLessThanOrEqual(1);
  await page.getByRole('button', {name:'View QR', exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('heading', {name:'Red Tag QR', exact:true})).toBeVisible();
  await expect(page.getByRole('dialog').locator('svg > title')).toContainText('/5s/red/'+id);
  await expect(page.getByRole('dialog').getByText('Scan to view Red Tag', {exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);

  await page.getByRole('button', {name:'View identification image 5', exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('img', {name:'detail.png', exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  await page.evaluate(() => localStorage.setItem('five-s-demo-role','leader'));
  await page.reload();
  await page.getByRole('button', {name:'Keep', exact:true}).click();
  await page.getByLabel('Keep Justification', {exact:true}).fill('Keep the item after inspecting all photos');
  await page.getByRole('button', {name:'Confirm Keep & Close', exact:true}).click();
  await expect(page.getByText('Kept · Closed', {exact:true})).toBeVisible();
  await page.getByRole('button', {name:'View Report', exact:true}).click();
  await expect(page.getByRole('heading', {name:'Red Tag Report', exact:true})).toBeVisible();
  for (const name of ['side.png','back.png','top.png','bottom.png','detail.png']) await expect(page.getByRole('img', {name, exact:true})).toBeVisible();
});
